"""Generate a real entry page for every clean URL (routes/<route>/index.html).

GitHub Pages serves files, so /tierlist only works if tierlist/index.html exists. Every entry is a copy of
src/index.html with a <base> that points back to the site root, so the shared css/, js/, assets/ and data/ resolve.

Run after changing src/index.html, SITE.pages or a character's slug in data/game.json:
    python3 tools/build_routes.py            write the entries
    python3 tools/build_routes.py --check    only verify them (check_all.py runs this)
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
MARKER = '<!-- Generated by tools/build_routes.py. Edit src/index.html instead. -->\n'
SITE_URL = 'https://agandaurcze.github.io/GBF-Relink-Endless-Ragnarok/'   # where GitHub Pages publishes the site
SITE_PATH = '/GBF-Relink-Endless-Ragnarok/'


def entries():
    game = json.loads((ROOT / 'data' / 'game.json').read_text(encoding='utf-8'))
    pages = game['SITE']['pages']
    shell = (ROOT / 'src' / 'index.html').read_text(encoding='utf-8')
    yield ROOT / 'routes' / 'index.html', MARKER + shell
    # GitHub Pages answers any unknown address with 404.html, at any depth, so its base is the absolute site path.
    yield ROOT / 'routes' / '404.html', MARKER + shell.replace('<base href="./">', f'<base href="{SITE_PATH}">', 1)
    routes = {p['route'] for p in pages} | {f'characters/{c["slug"]}' for c in game['CHARACTERS'] if c.get('slug')}
    for route in sorted(routes - {''}):
        if any(part in ('', '.', '..') for part in route.split('/')):
            raise ValueError(f'Invalid route: {route!r}')
        base = '../' * len(route.split('/'))
        yield ROOT / 'routes' / route / 'index.html', MARKER + shell.replace('<base href="./">', f'<base href="{base}">', 1)


def main():
    check = '--check' in sys.argv
    generated = list(entries())
    bad = []
    for path, html in generated:
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != html:
                bad.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(html, encoding='utf-8', newline='\n')
    expected = {p for p, _ in generated}
    for path in [*(ROOT / 'routes').glob('**/index.html'), *(ROOT / 'routes').glob('404.html')]:
        if path not in expected:
            if check:
                bad.append(f'{path.relative_to(ROOT)} (no longer a page)')
            else:
                path.unlink()
                for parent in path.parents:
                    if parent == ROOT / 'routes' or any(parent.iterdir()):
                        break
                    parent.rmdir()
    if bad:
        print('Route entries out of date. Run python3 tools/build_routes.py:\n' + '\n'.join(bad))
        return 1
    print(f'Route entries OK: {len(generated)} clean URLs.' if check else f'Wrote {len(generated)} route entries.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
